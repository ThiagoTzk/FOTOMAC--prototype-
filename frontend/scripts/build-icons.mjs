// Turns the SVGs exported from Figma (assets/icons/*.svg) into src/components/icons/svgs.ts.
// Run after adding or replacing an icon:  node scripts/build-icons.mjs
// The SVG drawings are kept exactly as exported; only attributes React Native does not
// understand are removed, and internal ids get a per-icon prefix (duplicated ids such as
// "clip0_0_6" would make one icon steal another's clipping on the web).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/icons/', import.meta.url);
const out = new URL('../src/components/icons/svgs.ts', import.meta.url);

const entries = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort().map((file) => {
  const name = file.replace('.svg', '');
  const prefix = name.replace(/[^a-z0-9]/gi, '_');
  const xml = readFileSync(new URL(file, dir), 'utf8')
    .replace(/\s(style|preserveAspectRatio|overflow)="[^"]*"/g, '')
    .replace(/id="([^"]+)"/g, `id="${prefix}_$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${prefix}_$1)`)
    .replace(/\s+/g, ' ')
    .trim();
  return `  '${name}': ${JSON.stringify(xml)},`;
});

writeFileSync(out, `// GENERATED by scripts/build-icons.mjs from assets/icons — do not edit by hand.\nexport const SVGS = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof SVGS;\n`);
console.log(`${entries.length} ícones gerados em src/components/icons/svgs.ts`);
